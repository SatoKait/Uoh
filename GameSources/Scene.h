#pragma once

#include "stdafx.h"

namespace basecross {

	//--------------------------------------------------------------------------------------
	///	ゲームシーン
	//--------------------------------------------------------------------------------------
	class Scene : public SceneBase {
	public:
		int m_Score;

		//--------------------------------------------------------------------------------------
		 /*!
		@brief リソースの追加
		@return	リソースのファイルの追加をする
		*/
		//--------------------------------------------------------------------------------------
		void CreateResourses();

	public:
		//--------------------------------------------------------------------------------------
		/*!
		@brief コンストラクタ
		*/
		//--------------------------------------------------------------------------------------
		Scene(
		) :
			SceneBase(),
			m_Score(0)
		{}
		//--------------------------------------------------------------------------------------
		/*!
		@brief デストラクタ
		*/
		//--------------------------------------------------------------------------------------
		virtual ~Scene();
		//--------------------------------------------------------------------------------------
		/*!
		@brief 初期化
		@return	なし
		*/
		//--------------------------------------------------------------------------------------
		virtual void OnCreate() override;
		//--------------------------------------------------------------------------------------
		/*!
		@brief イベント取得
		@return	なし
		*/
		//--------------------------------------------------------------------------------------
		virtual void OnEvent(const shared_ptr<Event>& event) override;

		// スコアをAdd
		void SetScore(int score) {
			m_Score = score;
		}

		// スコアを足す
		void AddScore(int score) {
			m_Score += score;
		}

		// スコアを取得する
		int GetScore() {
			return m_Score;
		}
	};
}

//end basecross
